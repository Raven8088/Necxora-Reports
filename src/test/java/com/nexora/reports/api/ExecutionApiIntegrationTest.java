    @Test
    void executesAPlanGeneratedBySemanticEndToEnd() throws Exception {
        UUID planId = PlanFixtures.planId(PlanFixtures.tree(PlanFixtures.SINGLE_OBJECT));
        JsonNode body = body(execute(runner(TENANT), SOURCE, planId, null)
                .andExpect(status().isOk())
                .andExpect(header().exists(ExecutionController.EXECUTION_ID_HEADER))
                .andExpect(header().exists(CorrelationIdFilter.HEADER)));

        assertThat(body.get("validity").asString()).isEqualTo("CURRENT");
        assertThat(body.get("planId").asString()).isEqualTo(planId.toString());
        assertThat(body.get("planFingerprint").asString())
                .isEqualTo(PlanFixtures.tree(PlanFixtures.SINGLE_OBJECT).get("fingerprint").asString());
        assertThat(body.get("columns").toString()).isEqualTo("[{\"name\":\"fecha\",\"role\":\"DIMENSION\","
                + "\"type\":\"DATE\"},{\"name\":\"nota\",\"role\":\"DIMENSION\",\"type\":\"TEXT\"},"
                + "{\"name\":\"suma_valor\",\"role\":\"METRIC\",\"type\":\"NUMERIC\"},"
                + "{\"name\":\"num_lecturas\",\"role\":\"METRIC\",\"type\":\"INTEGER\"}]");
        assertThat(body.get("rows").toString()).isEqualTo("[[\"2026-01-01\",\"revisar\",\"200.500\",1]]");
        assertThat(body.get("rowCount").asInt()).isEqualTo(1);
        assertThat(body.get("truncated").asBoolean()).isFalse();
        assertThat(body.get("maxRows").asInt()).isEqualTo(500);
        assertThat(body.get("warnings")).isEmpty();
        assertThat(body.toString()).doesNotContainIgnoringCase("select").doesNotContain("reader-test-password");

        // Semantic was called only with the tenant's own service token: data source, plan, validity twice.
        assertThat(TestPlatform.calls()).extracting(TestPlatform.Call::tenant).containsOnly(TENANT.toString());
        assertThat(TestPlatform.calls()).extracting(TestPlatform.Call::path).containsExactly(SOURCE_PATH,
                SOURCE_PATH + "/logical-plans/" + planId, SOURCE_PATH + "/logical-plans/" + planId + "/validity",
                SOURCE_PATH + "/logical-plans/" + planId + "/validity");

        ExecutionAuditRecord audit = latestAudit(TENANT);
        assertThat(audit.executionId().toString()).isEqualTo(body.get("executionId").asString());
        assertThat(audit.outcome()).isEqualTo(ExecutionAuditRecord.Outcome.SUCCEEDED);
        assertThat(audit.planId()).isEqualTo(planId);
        assertThat(audit.requesterType()).isEqualTo("HUMAN");
        assertThat(audit.validityStatus()).isEqualTo("CURRENT");
        assertThat(audit.rowCount()).isEqualTo(1);
        assertThat(auditRowAsText(audit.executionId())).doesNotContain("revisar", "200.5", "measurements",
                "reader");
    }

