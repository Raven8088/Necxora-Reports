    private static void register(ObjectNode envelope, int validityStatus, String validityBody) {
        UUID planId = PlanFixtures.planId(envelope);
        String planPath = SOURCE_PATH + "/logical-plans/" + planId;
        TestPlatform.semantic(TENANT, planPath, 200, PlanFixtures.JSON.writeValueAsString(envelope));
        TestPlatform.semantic(TENANT, planPath + "/validity", validityStatus, validityBody.isEmpty() ? "{}"
                : validityBody.contains("\"planId\"") ? validityBody.replaceFirst(
                "\"planId\" : \"[0-9a-f-]+\"", "\"planId\" : \"" + planId + "\"") : validityBody);
    }

    private static String runner(UUID tenant) {
        return TestPlatform.userToken(tenant, "HUMAN", "REPORT_RUNNER");
    }

    private static String path(UUID source, UUID planId) {
        return "/api/v1/data-sources/" + source + "/plans/" + planId + "/executions";
    }

    private ResultActions execute(String token, UUID source, UUID planId, String body) throws Exception {
        var request = post(path(source, planId)).header(HttpHeaders.AUTHORIZATION, "Bearer " + token);
        if (body != null) {
            request = request.contentType(MediaType.APPLICATION_JSON).content(body);
        }
        return mvc.perform(request);
    }

    private static JsonNode body(ResultActions actions) throws Exception {
        MvcResult result = actions.andReturn();
        return PlanFixtures.JSON.readTree(result.getResponse().getContentAsString());
    }

    private static JsonNode problem(ResultActions actions, int status, String code) throws Exception {
        actions.andExpect(status().is(status))
                .andExpect(header().string(HttpHeaders.CONTENT_TYPE, MediaType.APPLICATION_PROBLEM_JSON_VALUE))
                .andExpect(jsonPath("$.code").value(code))
                .andExpect(jsonPath("$.correlationId").exists());
        JsonNode problem = body(actions);
        assertThat(problem.toString()).doesNotContain("Exception", "at com.", "reader-test-password",
                "secret-tenant");
        return problem;
    }

    private ExecutionAuditRecord latestAudit(UUID tenant) {
        return auditRepository.findByTenant(tenant, 1).get(0);
    }

    private static String auditRowAsText(UUID executionId) throws SQLException {
        try (Connection c = TestDatabase.superuser("nexora_reports"); Statement s = c.createStatement();
             ResultSet rs = s.executeQuery("SELECT row_to_json(a)::text FROM reports.report_execution_audit a"
                     + " WHERE execution_id = '" + executionId + "'")) {
            rs.next();
            return rs.getString(1);
        }
    }

