    @Test
    void anotherTenantNeverReachesThisTenantsSourceOrPlans() throws Exception {
        UUID planId = PlanFixtures.planId(PlanFixtures.tree(PlanFixtures.SINGLE_OBJECT));
        // No read-only connection exists for (other tenant, this source): refused before any call to Semantic.
        problem(execute(runner(OTHER_TENANT), SOURCE, planId, null), 409, "data_source_not_configured");
        assertThat(TestPlatform.calls()).isEmpty();
        // Through its own source, Semantic (called with the other tenant's service token) does not know the plan.
        problem(execute(runner(OTHER_TENANT), OTHER_SOURCE, planId, null), 404, "not_found");
        assertThat(TestPlatform.calls()).extracting(TestPlatform.Call::tenant)
                .containsOnly(OTHER_TENANT.toString());
        // Audit records are kept per tenant.
        List<ExecutionAuditRecord> other = auditRepository.findByTenant(OTHER_TENANT, 50);
        assertThat(other).hasSize(2).allSatisfy(r -> assertThat(r.tenantId()).isEqualTo(OTHER_TENANT));
        List<UUID> otherIds = other.stream().map(ExecutionAuditRecord::executionId).toList();
        assertThat(auditRepository.findByTenant(TENANT, 500)).extracting(ExecutionAuditRecord::executionId)
                .doesNotContainAnyElementsOf(otherIds);
    }

