package com.nexora.reports.support;

import com.nimbusds.jose.JOSEException;
import com.nimbusds.jose.JWSAlgorithm;
import com.nimbusds.jose.JWSHeader;
import com.nimbusds.jose.crypto.RSASSASigner;
import com.nimbusds.jose.crypto.RSASSAVerifier;
import com.nimbusds.jose.jwk.JWKSet;
import com.nimbusds.jose.jwk.RSAKey;
import com.nimbusds.jose.jwk.gen.RSAKeyGenerator;
import com.nimbusds.jwt.JWTClaimsSet;
import com.nimbusds.jwt.SignedJWT;
import com.sun.net.httpserver.HttpExchange;
import com.sun.net.httpserver.HttpServer;

import java.io.IOException;
import java.io.OutputStream;
import java.io.UncheckedIOException;
import java.net.InetAddress;
import java.net.InetSocketAddress;
import java.nio.charset.StandardCharsets;
import java.time.Duration;
import java.time.Instant;
import java.util.Base64;
import java.util.Collection;
import java.util.Date;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.CopyOnWriteArrayList;

/**
 * Local stand-ins for the platform around Reports, started once per JVM on a loopback port:
 * <ul>
 *   <li>an OpenID Connect provider (discovery, JWKS and a client-credentials token endpoint) issuing real RS256
 *       tokens, like Keycloak;</li>
 *   <li>a fake Nexora Semantic under {@code /semantic} that only accepts service tokens of that provider with the
 *       Semantic audience and the REPORTS_CLIENT role, and answers per tenant (taken from the token), exactly as
 *       Semantic scopes everything by the token's tenant. Responses are the documents generated by Semantic.</li>
 * </ul>
 */
public final class TestPlatform {

    public static final String REPORTS_AUDIENCE = "nexora-reports";
    public static final String SEMANTIC_AUDIENCE = "nexora-semantic";
    private static final String REALM = "/realms/test";

    private static final RSAKey KEY = generate("trusted");
    private static final RSAKey UNTRUSTED = generate("untrusted");
    private static final Map<String, Client> CLIENTS = new ConcurrentHashMap<>();
    private static final Map<String, Response> SEMANTIC = new ConcurrentHashMap<>();
    private static final List<Call> CALLS = new CopyOnWriteArrayList<>();
    private static String base;

    /** A registered service client: its tokens always carry {@code tenant}. */
    private record Client(String secret, String tenant) {
    }

    public record Response(int status, String body) {
    }

    /** A call received by fake Semantic: the tenant claim of the token used and the path. */
    public record Call(String tenant, String path) {
    }

    private TestPlatform() {
    }

    public static synchronized String base() {
        if (base == null) {
            start();
        }
        return base;
    }

    public static String issuer() {
        return base() + REALM;
    }

    public static String tokenUri() {
        return issuer() + "/protocol/openid-connect/token";
    }

    public static String semanticUrl() {
        return base() + "/semantic";
    }

    public static void registerClient(String clientId, String secret, UUID tenant) {
        CLIENTS.put(clientId, new Client(secret, tenant == null ? null : tenant.toString()));
    }

    public static void semantic(UUID tenant, String path, int status, String body) {
        SEMANTIC.put(tenant + " " + path, new Response(status, body));
    }

    public static List<Call> calls() {
        return List.copyOf(CALLS);
    }

    public static void clearCalls() {
        CALLS.clear();
    }

    // --- user tokens ---

    public static String userToken(UUID tenant, String type, String... roles) {
        return sign(KEY, claims("user-" + UUID.randomUUID(), REPORTS_AUDIENCE, tenant == null ? null
                : tenant.toString(), type, List.of(roles), Instant.now().plus(Duration.ofMinutes(5))));
    }

    /** User token with additional, arbitrary claims (for example claims a consumer could try to inject). */
    public static String userTokenWithClaims(UUID tenant, String type, Map<String, Object> extra, String... roles) {
        JWTClaimsSet.Builder builder = new JWTClaimsSet.Builder(claims("user-" + UUID.randomUUID(), REPORTS_AUDIENCE,
                tenant.toString(), type, List.of(roles), Instant.now().plus(Duration.ofMinutes(5))));
        extra.forEach(builder::claim);
        return sign(KEY, builder.build());
    }

    public static String expiredUserToken(UUID tenant) {
        return sign(KEY, claims("user-expired", REPORTS_AUDIENCE, tenant.toString(), "HUMAN",
                List.of("REPORT_RUNNER"), Instant.now().minus(Duration.ofMinutes(5))));
    }

    public static String tokenWithAudience(UUID tenant, String audience) {
        return sign(KEY, claims("user-aud", audience, tenant.toString(), "HUMAN", List.of("REPORT_RUNNER"),
                Instant.now().plus(Duration.ofMinutes(5))));
    }

    public static String untrustedToken(UUID tenant) {
        return sign(UNTRUSTED, claims("user-untrusted", REPORTS_AUDIENCE, tenant.toString(), "HUMAN",
                List.of("REPORT_RUNNER"), Instant.now().plus(Duration.ofMinutes(5))));
    }

    // --- server ---

    private static void start() {
        try {
            HttpServer server = HttpServer.create(new InetSocketAddress(InetAddress.getByName("127.0.0.1"), 0), 0);
            base = "http://127.0.0.1:" + server.getAddress().getPort();
            String issuer = base + REALM;
            String discovery = """
                    {"issuer":"%1$s","jwks_uri":"%1$s/protocol/openid-connect/certs",
                     "authorization_endpoint":"%1$s/protocol/openid-connect/auth",
                     "token_endpoint":"%1$s/protocol/openid-connect/token",
                     "response_types_supported":["code"],"subject_types_supported":["public"],
                     "id_token_signing_alg_values_supported":["RS256"]}""".formatted(issuer);
            server.createContext(REALM + "/.well-known/openid-configuration", e -> respond(e, 200, discovery));
            server.createContext(REALM + "/protocol/openid-connect/certs",
                    e -> respond(e, 200, new JWKSet(KEY.toPublicJWK()).toString()));
            server.createContext(REALM + "/protocol/openid-connect/token", TestPlatform::token);
            server.createContext("/semantic/", TestPlatform::semantic);
            server.setExecutor(java.util.concurrent.Executors.newFixedThreadPool(8));
            server.start();
            Runtime.getRuntime().addShutdownHook(new Thread(() -> server.stop(0)));
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static void token(HttpExchange exchange) throws IOException {
        String authorization = exchange.getRequestHeaders().getFirst("Authorization");
        String body = new String(exchange.getRequestBody().readAllBytes(), StandardCharsets.UTF_8);
        if (!"POST".equals(exchange.getRequestMethod()) || authorization == null
                || !authorization.startsWith("Basic ") || !body.contains("grant_type=client_credentials")) {
            respond(exchange, 400, "{\"error\":\"invalid_request\"}");
            return;
        }
        String[] credentials = new String(Base64.getDecoder().decode(authorization.substring(6)),
                StandardCharsets.UTF_8).split(":", 2);
        String clientId = java.net.URLDecoder.decode(credentials[0], StandardCharsets.UTF_8);
        String secret = credentials.length > 1 ? java.net.URLDecoder.decode(credentials[1], StandardCharsets.UTF_8)
                : "";
        Client client = CLIENTS.get(clientId);
        if (client == null || !client.secret().equals(secret)) {
            respond(exchange, 401, "{\"error\":\"invalid_client\"}");
            return;
        }
        String token = sign(KEY, claims("service-account-" + clientId, SEMANTIC_AUDIENCE, client.tenant(),
                "SERVICE", List.of("REPORTS_CLIENT"), Instant.now().plus(Duration.ofMinutes(5))));
        respond(exchange, 200, "{\"access_token\":\"" + token + "\",\"token_type\":\"Bearer\",\"expires_in\":300}");
    }

    /** Fake Semantic: authenticates like Semantic and serves registered documents for the token's tenant. */
    private static void semantic(HttpExchange exchange) throws IOException {
        String path = exchange.getRequestURI().getRawPath().substring("/semantic".length());
        String authorization = exchange.getRequestHeaders().getFirst("Authorization");
        String tenant = null;
        try {
            SignedJWT jwt = SignedJWT.parse(authorization.substring("Bearer ".length()));
            JWTClaimsSet claims = jwt.getJWTClaimsSet();
            Object roles = claims.getClaim("roles");
            if (!jwt.verify(new RSASSAVerifier(KEY.toRSAPublicKey()))
                    || !claims.getAudience().contains(SEMANTIC_AUDIENCE)
                    || !(roles instanceof Collection<?> list && list.contains("REPORTS_CLIENT"))
                    || claims.getExpirationTime().before(new Date())) {
                throw new IllegalArgumentException("rejected");
            }
            tenant = claims.getStringClaim("tenant");
        } catch (Exception e) {
            CALLS.add(new Call(null, path));
            respond(exchange, 401, "{\"code\":\"unauthorized\"}");
            return;
        }
        CALLS.add(new Call(tenant, path));
        Response response = SEMANTIC.get(tenant + " " + path);
        if (response == null) {
            respond(exchange, 404, "{\"status\":404,\"code\":\"not_found\",\"detail\":\"Resource not found\"}");
            return;
        }
        respond(exchange, response.status(), response.body());
    }

    private static void respond(HttpExchange exchange, int status, String json) throws IOException {
        byte[] body = json.getBytes(StandardCharsets.UTF_8);
        exchange.getResponseHeaders().add("Content-Type", "application/json");
        exchange.sendResponseHeaders(status, body.length);
        try (OutputStream out = exchange.getResponseBody()) {
            out.write(body);
        }
    }

    // --- tokens ---

    private static JWTClaimsSet claims(String subject, String audience, String tenant, String type,
                                       List<String> roles, Instant expiresAt) {
        JWTClaimsSet.Builder builder = new JWTClaimsSet.Builder()
                .issuer(issuer())
                .subject(subject)
                .audience(audience)
                .issueTime(Date.from(Instant.now().minusSeconds(5)))
                .expirationTime(Date.from(expiresAt))
                .claim("roles", roles);
        if (tenant != null) {
            builder.claim("tenant", tenant);
        }
        if (type != null) {
            builder.claim("principal_type", type);
        }
        return builder.build();
    }

    private static String sign(RSAKey key, JWTClaimsSet claims) {
        try {
            SignedJWT jwt = new SignedJWT(new JWSHeader.Builder(JWSAlgorithm.RS256).keyID(key.getKeyID()).build(),
                    claims);
            jwt.sign(new RSASSASigner(key));
            return jwt.serialize();
        } catch (JOSEException e) {
            throw new IllegalStateException(e);
        }
    }

    private static RSAKey generate(String id) {
        try {
            return new RSAKeyGenerator(2048).keyID(id).generate();
        } catch (JOSEException e) {
            throw new IllegalStateException(e);
        }
    }
}
